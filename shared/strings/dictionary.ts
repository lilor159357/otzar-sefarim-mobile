export type StringsDictionary = typeof DEFAULT_STRINGS;

type JoinKey<K extends string, P extends string> = `${K}.${P}`;

type DeepLeafEntries<T> = {
  [K in keyof T & string]: T[K] extends string
    ? { key: K; value: T[K] }
    : DeepLeafEntries<T[K]> extends infer Sub
      ? Sub extends { key: infer SK extends string; value: infer SV extends string }
        ? { key: JoinKey<K, SK>; value: SV }
        : never
      : never;
}[keyof T & string];

export type StringKey = DeepLeafEntries<StringsDictionary>["key"];
export type StringNamespace = keyof StringsDictionary;

export type StringValueFor<K extends StringKey> = Extract<
  DeepLeafEntries<StringsDictionary>,
  { key: K }
>["value"];

type ExtractPlaceholderNames<S extends string> =
  S extends `${string}{${infer Param}}${infer Rest}`
    ? Param | ExtractPlaceholderNames<Rest>
    : never;

export type StringParams<K extends StringKey> = {
  [P in ExtractPlaceholderNames<StringValueFor<K>>]: string | number;
};

export type ParamArgs<K extends StringKey> =
  ExtractPlaceholderNames<StringValueFor<K>> extends never
    ? []
    : [params: StringParams<K>];

